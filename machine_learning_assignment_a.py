import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor

"""# Load Dataset"""

df = pd.read_csv('/content/House Price Prediction Dataset.csv')
df.head()

"""# Data Cleaning"""

df.isnull(df).sum()

"""# Convert Categorical Data to numaric"""

le = LabelEncoder()
for col in df.columns:
  if df[col].dtype == 'object':
    df[col] = le.fit_transform(df[col])
df.head()

"""# EDA"""

plt.figure(figsize=(12,8))
sns.heatmap(df.corr(), cmap="coolwarm")
plt.title("Correlation Heatmap")
plt.show()

plt.figure(figsize=(8,5))
sns.histplot(df['Price'], kde=True)
plt.title("Distribution of House Prices")
plt.xlabel("Price")
plt.ylabel("Frequency")
plt.show()

if 'Area' in df.columns:
  plt.figure(figsize=(8,5))
  sns.scatterplot(x=df['Area'], y=df['Price'])
  plt.title("Area vs Price")
  plt.xlabel("Area")
  plt.show()

"""#Define features and Trget"""

x = df.drop('Price', axis=1)
y = df['Price']
x_train, x_test, y_train, y_test = train_test_split(
    x, y, test_size=0.2, random_state=42)
x_train.shape,
x_test.shape,

"""# Model 1
Linear Regression
"""

from sklearn.linear_model import LinearRegression
r = LinearRegression()
r.fit(x_train, y_train)
r_pred = r.predict(x_test)
r2_score(y_test, r_pred)
mean_absolute_error(y_test, r_pred)
np.sqrt(mean_squared_error(y_test, r_pred))

"""# Decosion Tree Reguration"""

df = DecisionTreeRegressor(random_state=42)
df.fit(x_train, y_train)
df_pred = df.predict(x_test)
r2_score(y_test, df_pred)
mean_absolute_error(y_test, df_pred)
np.sqrt(mean_squared_error(y_test, df_pred))

"""# Random forest Regurassor"""

rf = RandomForestRegressor(
    n_estimators=100,
    random_state=42
)
rf.fit(x_train, y_train)
rf_pred = rf.predict(x_test)
r2_score(y_test, rf_pred)
mean_absolute_error(y_test, rf_pred)
np.sqrt(mean_squared_error(y_test, rf_pred))

"""# Accuracy"""

result = pd.DataFrame({
    'Model': ['Linear Regression',
              'Decision Tree Regressor',
              'Random Forest Regressor'
              ],
    'R2 Score': [
        r2_score(y_test, r_pred),
        r2_score(y_test, df_pred),
        r2_score(y_test, rf_pred)
    ],
    'MAE': [
        mean_absolute_error(y_test, r_pred),
        mean_absolute_error(y_test, df_pred),
        mean_absolute_error(y_test, rf_pred)
    ],
    'RMSE': [
        np.sqrt(mean_squared_error(y_test, r_pred)),
        np.sqrt(mean_squared_error(y_test, df_pred)),
        np.sqrt(mean_squared_error(y_test, rf_pred))
    ]
})

display(result)